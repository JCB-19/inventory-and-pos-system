//================DTOs OR Data Transfer Objects.=======================

// Full dashboard response structure returned to frontend
// Matches the DashboardSummary interface in frontend TypeScript
#[derive(Serialize)]
#[allow(dead_code)]
pub struct DashboardSummary {

    // Total revenue from all matching orders
    pub total_revenue: f64,

    // Total quantity of all products sold
    pub total_quantity_sold: i64,

    // Total number of completed orders
    pub total_sold: i64,

    // Average value of each order
    pub avg_order_value: f64,

    // Top 5 best-selling products
    pub top_products: Vec<TopProduct>,

    // Most recent transactions
    pub recent_transactions: Vec<RecentTransaction>,

    // Products with low stock
    pub low_stock: Vec<LowStockItem>,
}

// Struct used for totals query result
#[derive(sqlx::FromRow)]
pub struct TotalsRow {

    // Total revenue from query
    pub total_revenue: f64,

    // Number of orders
    pub total_orders: i64,

    // Average order value
    pub avg_order_value: f64,
}

// Struct used for total sold query result
#[derive(sqlx::FromRow)]
pub struct TotalSoldRow {

    // Total quantity sold
    pub total_sold: i64,
}

// Top 5 products ranked by quantity sold
#[derive(Debug, Serialize, FromRow)]
pub struct TopProduct {

    // Product name
    pub name: String,

    // Total quantity sold
    pub quantity: i64,

    // Total revenue generated by product
    pub revenue: f64,
}

// Last 10 orders sorted by newest first
#[derive(sqlx::FromRow, serde::Serialize, serde::Deserialize)]
pub struct RecentTransaction {

    // Order ID
    pub id: i32,

    // Date and time order was created
    #[serde(with = "time::serde::iso8601")]
    pub created_at: OffsetDateTime,

    // Total number of items in order
    pub items: i64,

    // Total order amount
    pub total: f64,
}

// Products with low stock levels
#[derive(Debug, Serialize, FromRow)]
pub struct LowStockItem {

    // Product name
    pub name: String,

    // Remaining stock count
    pub stock: i32,
}

// Query parameters received from frontend
#[derive(serde::Deserialize)]
pub struct DashboardQuery {
    // Optional date range filter
    // Example: day, week, month
    pub range: Option<String>,

}

