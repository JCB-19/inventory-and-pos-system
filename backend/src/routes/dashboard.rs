//=========================API ENDPOINTS==============================

// GET endpoint for dashboard data
#[get("/dashboard")]
pub async fn dashboard(

    // Query parameters from frontend
    query: web::Query<DashboardQuery>,

    // Shared application state
    service: web::Data<AppState>,

    // Incoming HTTP request
    req: HttpRequest,
) -> impl Responder {

    // Read JWT claims stored by authentication middleware
    let claims = match req.extensions().get::<Claims>().cloned() {

        // Claims found
        Some(c) => c,

        // Unauthorized if claims missing
        None => return HttpResponse::Unauthorized().body("Unauthorized"),
    };

    // Call dashboard service logic
    match service.dashboards.dashboard(claims,query.range.clone()).await {

        // Success response
        Ok(dashboardsummary) => HttpResponse::Ok().json(serde_json::json!({
            "message": "Dashboard fetched successfully",
            "data": dashboardsummary
        })),

        // Error handling
        Err(e) => match e {

            // Database error response
            CustomError::DatabaseError => {
                HttpResponse::InternalServerError().body(e.to_string())
            }

            // Unauthorized response
            CustomError::Unauthorized => {
                HttpResponse::Unauthorized().body(e.to_string())
            }

        }
    }
}

