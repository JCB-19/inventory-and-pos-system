//============OOP METHODS OR STRUCT IMPLEMENTATION IN RUST============

impl DashboardService {

    // Constructor function for DashboardService
    pub fn new(pool: PgPool) -> Self {

        // Return new service instance
        Self{pool}
    }

    // ============================================================
    // ORDER FILTERS
    // Used for:
    // - totals
    // - total sold
    // - top products
    // - recent transactions
    // ============================================================

    // Reusable function for filtering order queries
    // based on role and time range
    fn apply_order_filters(
        query: &mut QueryBuilder<Postgres>,
        claim: &Claims,
        range: &Option<String>,
    ) -> Result<(), CustomError> {

        // ================= ROLE FILTERS =================

        // Apply role-based access restrictions
        match claim.role.as_str() {

            // Admin can see all company orders
            "admin" => {
                query.push(" WHERE company_info.company_name = ");
                query.push_bind(claim.companyname.clone());
            }

            // Manager can only see orders from their branch
            "manager" => {
                query.push(" WHERE company_info.company_name = ");
                query.push_bind(claim.companyname.clone());

                query.push(" AND company_info.branch_name = ");
                query.push_bind(claim.branchname.clone());
            }

            // POS staff can only see their own orders
            "pos_staff" => {
                query.push(" WHERE company_info.company_name = ");
                query.push_bind(claim.companyname.clone());

                query.push(" AND company_info.branch_name = ");
                query.push_bind(claim.branchname.clone());

                query.push(" AND orders.user_id = ");
                query.push_bind(claim.id.clone());
            }

            // Reject invalid roles
            _ => {
                return Err(CustomError::Unauthorized);
            }
        }

        // ================= TIME FILTERS =================

        // Apply optional date range filters
        match range.as_deref() {

            // Filter today's orders
            Some("day") => {
                query.push(
                    " AND orders.created_at >= date_trunc('day', NOW())"
                );
            }

            // Filter this week's orders
            Some("week") => {
                query.push(
                    " AND orders.created_at >= date_trunc('week', NOW())"
                );
            }

            // Filter this month's orders
            Some("month") => {
                query.push(
                    " AND orders.created_at >= date_trunc('month', NOW())"
                );
            }

            // No time filter
            _ => {}
        }   

        Ok(())
    }



    // ============================================================
    // PRODUCT FILTERS
    // Used for:
    // - low stock
    // ============================================================

    // Reusable product filter function
    fn apply_product_filters(
        query: &mut QueryBuilder<Postgres>,
        claim: &Claims,
    ) -> Result<(), CustomError> {

        // Apply product access rules based on user role
        match claim.role.as_str() {

            // Admin can see all products in company
            "admin" => {
                query.push(" AND company_info.company_name = ");
                query.push_bind(claim.companyname.clone());
            }

            // Manager can only see products from their branch
            "manager" => {
                query.push(" AND company_info.company_name = ");
                query.push_bind(claim.companyname.clone());

                query.push(" AND company_info.branch_name = ");
                query.push_bind(claim.branchname.clone());
            }

            // POS staff can only see products they own
            "pos_staff" => {
                query.push(" AND company_info.company_name = ");
                query.push_bind(claim.companyname.clone());

                query.push(" AND company_info.branch_name = ");
                query.push_bind(claim.branchname.clone());

                query.push(" AND products.user_id = ");
                query.push_bind(claim.id.clone());
            }

            // Reject unauthorized roles
            _ => {
                return Err(CustomError::Unauthorized);
            }
        }

        Ok(())
    }

    // Main dashboard business logic
    pub async fn dashboard(&self, claim: Claims, range: Option<String>) -> Result<serde_json::Value, CustomError> {
    
        // ── Step 1: Fetch totals summary ─────────────────────────────

        // Query for total revenue, order count, and average order value
        let mut  totals = sqlx::QueryBuilder::new(
            "SELECT
                COALESCE(SUM(total), 0)::float8           AS total_revenue,
                COUNT(*)::bigint                           AS total_orders,
                COALESCE(AVG(total), 0)::float8            AS avg_order_value
            FROM orders
            JOIN company_info ON orders.company_info_id = company_info.company_info_id"
        );

        // Apply reusable filters
        Self::apply_order_filters(
            &mut totals,
            &claim,
            &range,
        )?;

        // Execute totals query
        let totals_result: TotalsRow = totals
            .build_query_as::<TotalsRow>()
            .fetch_one(&self.pool)
            .await
            .map_err(|e| {
                eprintln!("Failed to fetch totals: {:?}", e);
                CustomError::DatabaseError
        })?;


        // ── Step 2: Fetch total items sold ──────────────────────────

        // Query total quantity sold
        let mut total_sold = sqlx::QueryBuilder::new(
        "SELECT COALESCE(SUM(order_items.quantity), 0)::bigint AS total_sold
            FROM order_items
            JOIN orders ON orders.orders_id = order_items.order_id
            JOIN company_info ON orders.company_info_id = company_info.company_info_id"
        );

        // Apply filters
        Self::apply_order_filters(
            &mut total_sold,
            &claim,
            &range,
        )?;

        // Execute query
        let total_sold_row: TotalSoldRow = total_sold
            .build_query_as::<TotalSoldRow>()
            .fetch_one(&self.pool)
            .await
            .map_err(|e| {
                eprintln!("Failed to fetch total sold: {:?}", e);
                CustomError::DatabaseError
        })?;

        // ── Step 3: Fetch top 5 products ────────────────────────────

        // Query top-selling products
        let mut top_products = sqlx::QueryBuilder::new(
            "SELECT
                products.product_name                              AS name,
                SUM(order_items.quantity)::bigint                    AS quantity,
                SUM(order_items.quantity * order_items.price)::float8         AS revenue
            FROM order_items
            JOIN products ON products.product_id = order_items.product_id
            JOIN orders ON orders.orders_id = order_items.order_id
            JOIN company_info ON orders.company_info_id = company_info.company_info_id"
        );

        // Apply filters
        Self::apply_order_filters(
            &mut top_products,
            &claim,
            &range,
        )?;

        // Group and limit results
        top_products.push(" GROUP BY products.product_name ORDER BY quantity DESC LIMIT 5");

        // Execute query
        let top_products_result: Vec<TopProduct> = top_products
            .build_query_as::<TopProduct>()
            .fetch_all(&self.pool)
            .await
            .map_err(|e| {
                eprintln!("Failed to fetch top products: {:?}", e);
                CustomError::DatabaseError
        })?;

        // ── Step 4: Fetch recent transactions ───────────────────────

        // Query latest orders
        let mut recent_transactions = sqlx::QueryBuilder::new(
            "SELECT
                orders.orders_id AS id,
                orders.created_at,
                orders.total::float8 AS total,
                COALESCE(SUM(order_items.quantity), 0)::bigint AS items
            FROM orders
            LEFT JOIN order_items ON order_items.order_id = orders.orders_id
            JOIN company_info ON orders.company_info_id = company_info.company_info_id"
        );

        // Apply filters
        Self::apply_order_filters(
            &mut recent_transactions,
            &claim,
            &range,
        )?;

        // Group and sort newest first
        recent_transactions.push(" GROUP BY orders.orders_id, orders.created_at, orders.total ORDER BY orders.created_at DESC LIMIT 10");
        
        // Execute query
        let recent_transactions_result: Vec<RecentTransaction> = recent_transactions
            .build_query_as::<RecentTransaction>()
            .fetch_all(&self.pool)
            .await
            .map_err(|e| {
                eprintln!("Failed to fetch recent transactions: {:?}", e);
                CustomError::DatabaseError
        })?;


        // ── Step 5: Fetch low stock products ────────────────────────

        // Query products with low stock
        let mut low_stock = sqlx::QueryBuilder::new(
            "SELECT product_name AS name, product_stock AS stock
            FROM products
            JOIN company_info ON products.company_info_id = company_info.company_info_id"
        );

        // Apply product filters
        Self::apply_product_filters(
            &mut low_stock,
            &claim,
        )?;

        // Sort lowest stock first
        low_stock.push(" AND product_stock <=10 ORDER BY product_stock ASC");

        // Execute query
        let low_stock_result: Vec<LowStockItem> = low_stock    
            .build_query_as::<LowStockItem>()
            .fetch_all(&self.pool)
            .await
            .map_err(|e| {
                eprintln!("Failed to fetch low stock products: {:?}", e);
                CustomError::DatabaseError
        })?;

        // ── Step 6: Return full dashboard response ──────────────────

        Ok(serde_json::json!(DashboardSummary {

            // Total revenue
            total_revenue: totals_result.total_revenue,

            // Total items sold
            total_quantity_sold: total_sold_row.total_sold,

            // Total order count
            total_sold: totals_result.total_orders,

            // Average order value
            avg_order_value: totals_result.avg_order_value,

            // Top-selling products
            top_products: top_products_result,

            // Recent orders
            recent_transactions: recent_transactions_result,

            // Low stock products
            low_stock: low_stock_result,
        }))
    }
    

}

